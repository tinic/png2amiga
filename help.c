/* Full 14-register 6845 CRTC init for 80x50 text (4-scan cells). */
static const unsigned char crtc_init[14] = {
    0x71, 0x50, 0x59, 0x0F, 0x7F, 0x06, 0x32, 0x70,
    0x02, 0x03, 0x20, 0x00, 0x00, 0x00
};

int main(void) {
    set_mode(0x03);               /* BIOS 80x25 color text */
    outb(0x3D8, 0x01);            /* video OFF, 80-col */
    for (unsigned i = 0; i < 14; ++i) {
        outb(0x3D4, (unsigned char)i);
        outb(0x3D5, crtc_init[i]);
    }
    blit_b800(help_data, sizeof(help_data));
    outb(0x3D8, 0x09);            /* video ON + blink OFF */
    (void)wait_key();
    set_mode(0x03);               /* BIOS mode-set restores 6845 */
    return 0;
}
