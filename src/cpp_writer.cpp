Result<void> write_atlas_pack(std::string_view base_path,
                              const atlas_pack::PackResult& pack,
                              const Options& opts) {
    auto ns_parts = split_namespace(opts.namespace_name);
    auto hpp_path = std::string{base_path} + ".hpp";
    auto cpp_path = std::string{base_path} + ".cpp";

    auto pal_elem_type = (opts.chipset == Chipset::ocs)
        ? std::string_view{"std::uint16_t"}
        : std::string_view{"std::uint32_t"};

    // Deduplicate sanitized enum names in case two inputs share a base stem.
    std::vector<std::string> enum_names(pack.entries.size());
    std::unordered_map<std::string, int> used;
    for (std::size_t i = 0; i < pack.entries.size(); ++i) {
        auto base = sanitize_ident(pack.entries[i].name);
        auto& n = used[base];
        enum_names[i] = (n == 0) ? base : std::format("{}_{}", base, n);
        ++n;
    }

    // -------------------- header --------------------
    {
        std::ofstream hpp{hpp_path};
        if (!hpp) {
            return std::unexpected{Error{ErrorCode::write_failed,
                std::format("cannot open {}", hpp_path)}};
        }
        hpp << "// Generated by png2amiga-assets — do not edit.\n";
        hpp << "#pragma once\n\n";
        hpp << "#include <array>\n";
        hpp << "#include <cstdint>\n\n";

        emit_ns_open(hpp, ns_parts);
        hpp << "\n";

        hpp << std::format("inline constexpr unsigned page_w           = {};\n", pack.page_w);
        hpp << std::format("inline constexpr unsigned page_h           = {};\n", pack.page_h);
        hpp << std::format("inline constexpr unsigned depth            = {};\n", pack.depth);
        hpp << std::format("inline constexpr unsigned page_bpr         = {};\n", pack.page_bpr);
        hpp << std::format("inline constexpr unsigned page_bytes       = {};\n", pack.page_bytes);
        hpp << std::format("inline constexpr unsigned num_pages        = {};\n", pack.pages.size());
        hpp << std::format("inline constexpr unsigned num_entries      = {};\n", pack.entries.size());
        hpp << std::format("inline constexpr unsigned palette_size     = {};\n", pack.palette.size());
        hpp << std::format("inline constexpr bool     has_mask         = {};\n",
                           pack.has_mask ? "true" : "false");
        if (pack.has_mask) {
            hpp << std::format("inline constexpr unsigned page_mask_bytes  = {};\n", pack.page_mask_bytes);
        }
        hpp << "\n";

        hpp <<
            "struct Entry {\n"
            "    std::uint8_t  page;\n"
            "    std::uint16_t x;          // 16-px aligned\n"
            "    std::uint16_t y;\n"
            "    std::uint16_t w;          // logical width\n"
            "    std::uint16_t h;\n"
            "    std::uint16_t w_padded;   // 16-aligned storage width\n"
            "};\n\n";

        // Named enum for type-safe lookup.
        hpp << "enum class Id : std::uint16_t {\n";
        for (std::size_t i = 0; i < pack.entries.size(); ++i) {
            hpp << std::format("    {}{},\n", enum_names[i],
                               i == 0 ? " = 0" : "");
        }
        hpp << "};\n\n";

        hpp << std::format(
            "extern const std::array<std::uint16_t, num_pages * (page_bytes / 2)> pages_data;\n");
        if (pack.has_mask) {
            hpp << std::format(
                "extern const std::array<std::uint16_t, num_pages * (page_mask_bytes / 2)> masks_data;\n");
        }
        hpp << std::format(
            "extern const std::array<Entry, num_entries> entries;\n");
        hpp << std::format(
            "extern const std::array<{}, palette_size> palette;\n\n", pal_elem_type);

        hpp <<
            "[[nodiscard]] constexpr const Entry& get(Id id) noexcept {\n"
            "    return entries[static_cast<std::size_t>(id)];\n"
            "}\n"
            "[[nodiscard]] constexpr const std::uint16_t* page_ptr(unsigned p) noexcept {\n"
            "    return pages_data.data() + static_cast<std::size_t>(p) * (page_bytes / 2);\n"
            "}\n";
        if (pack.has_mask) {
            hpp <<
                "[[nodiscard]] constexpr const std::uint16_t* mask_page_ptr(unsigned p) noexcept {\n"
                "    return masks_data.data() + static_cast<std::size_t>(p) * (page_mask_bytes / 2);\n"
                "}\n";
        }
        hpp << "\n";

        emit_ns_close(hpp, ns_parts);
    }

    // -------------------- source --------------------
    {
        std::ofstream cpp{cpp_path};
        if (!cpp) {
            return std::unexpected{Error{ErrorCode::write_failed,
                std::format("cannot open {}", cpp_path)}};
        }
        cpp << "// Generated by png2amiga-assets — do not edit.\n";
        cpp << "#include \"" << std::filesystem::path{hpp_path}.filename().string() << "\"\n";
        if (opts.chip_attr == "PA_ASSET_CHIP") {
            cpp << "#include \"pa/chip_attr.hpp\"\n";
        }
        cpp << "\n";

        emit_ns_open(cpp, ns_parts);
        cpp << "\n";

        // pages_data
        if (!opts.chip_attr.empty()) cpp << opts.chip_attr << "\n";
        cpp << "const std::array<std::uint16_t, num_pages * (page_bytes / 2)> pages_data = {\n";
        for (auto& p : pack.pages) emit_bitplane_words(cpp, p.data);
        cpp << "};\n\n";

        // masks_data
        if (pack.has_mask) {
            if (!opts.chip_attr.empty()) cpp << opts.chip_attr << "\n";
            cpp << "const std::array<std::uint16_t, num_pages * (page_mask_bytes / 2)> masks_data = {\n";
            for (auto& m : pack.masks) emit_bitplane_words(cpp, m);
            cpp << "};\n\n";
        }

        // entries
        cpp << "const std::array<Entry, num_entries> entries = {{\n";
        for (auto& e : pack.entries) {
            cpp << std::format(
                "    Entry{{ {}, {}, {}, {}, {}, {} }},\n",
                e.page, e.x, e.y, e.w, e.h, e.w_padded);
        }
        cpp << "}};\n\n";

        cpp << std::format("const std::array<{}, palette_size> palette = {{\n", pal_elem_type);
        emit_palette(cpp, pack.palette, opts.chipset);
        cpp << "};\n\n";

        emit_ns_close(cpp, ns_parts);
    }

    return {};
}

