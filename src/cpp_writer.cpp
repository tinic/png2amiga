// Split "a::b::c" into {"a","b","c"}.
std::vector<std::string> split_namespace(std::string_view s) {
    std::vector<std::string> out;
    std::size_t i = 0;
    while (i < s.size()) {
        auto j = s.find("::", i);
        if (j == std::string_view::npos) {
            out.emplace_back(s.substr(i));
            break;
        }
        out.emplace_back(s.substr(i, j - i));
        i = j + 2;
    }
    return out;
}

std::string basename_no_ext(std::string_view path) {
    std::filesystem::path p{std::string{path}};
    return p.stem().string();
}

std::string last_namespace_segment(std::string_view ns) {
    auto i = ns.rfind("::");
    return std::string{i == std::string_view::npos ? ns : ns.substr(i + 2)};
}

// Emit open/close of nested namespaces.
void emit_ns_open(std::ostream& os, const std::vector<std::string>& parts) {
    if (parts.empty()) return;
    os << "namespace ";
    for (std::size_t i = 0; i < parts.size(); ++i) {
        if (i) os << "::";
        os << parts[i];
    }
    os << " {\n";
}

void emit_ns_close(std::ostream& os, const std::vector<std::string>& parts) {
    if (parts.empty()) return;
    os << "} // namespace ";
    for (std::size_t i = 0; i < parts.size(); ++i) {
        if (i) os << "::";
        os << parts[i];
    }
    os << "\n";
}

// Emit palette entries as C++26 std::array literal.
// OCS: std::array<std::uint16_t, N> in 0x0RGB format.
// AGA: std::array<std::uint32_t, N> in 0x00RRGGBB format.
void emit_palette(std::ostream& os, std::span<const Color3f> pal,
                  Chipset chipset) {
    if (chipset == Chipset::ocs) {
        os << "    ";
        for (std::size_t i = 0; i < pal.size(); ++i) {
            os << std::format("0x{:04X}", palette::linear_to_ocs(pal[i]));
            if (i + 1 < pal.size()) os << ", ";
            if ((i + 1) % 8 == 0 && i + 1 < pal.size()) os << "\n    ";
        }
        os << "\n";
    } else {
        os << "    ";
        for (std::size_t i = 0; i < pal.size(); ++i) {
            os << std::format("0x{:08X}", palette::linear_to_aga(pal[i]));
            if (i + 1 < pal.size()) os << ", ";
            if ((i + 1) % 4 == 0 && i + 1 < pal.size()) os << "\n    ";
        }
        os << "\n";
    }
}

// Emit bitplane bytes as a std::array<std::uint16_t, N> literal
// (words are built big-endian, matching 68k native order).
void emit_bitplane_words(std::ostream& os,
                         std::span<const std::uint8_t> bytes) {
    auto nwords = bytes.size() / 2;
    constexpr std::size_t per_line = 12;
    for (std::size_t i = 0; i < nwords; ++i) {
        if (i % per_line == 0) os << "    ";
        auto hi = bytes[i * 2];
        auto lo = bytes[i * 2 + 1];
        std::uint16_t w = static_cast<std::uint16_t>((hi << 8) | lo);
        os << std::format("0x{:04X}", w);
        if (i + 1 < nwords) os << ",";
        if ((i + 1) % per_line == 0 || i + 1 == nwords) os << "\n";
        else os << " ";
    }
}

// Emit the tilemap as std::array<MapCell, N>. Raw u16 initializers.
void emit_tilemap(std::ostream& os, std::span<const tile_pack::MapCell> cells,
                  std::size_t per_row) {
    for (std::size_t i = 0; i < cells.size(); ++i) {
        if (i % per_row == 0) os << "    ";
        os << std::format("MapCell{{0x{:04X}}}", cells[i].raw);
        if (i + 1 < cells.size()) os << ",";
        if ((i + 1) % per_row == 0 || i + 1 == cells.size()) os << "\n";
        else os << " ";
    }
}

