Result<void> write_tile_pack(std::string_view base_path,
                             const tile_pack::PackResult& pack,
                             const Options& opts) {
    auto ns_parts = split_namespace(opts.namespace_name);
    auto short_name = last_namespace_segment(opts.namespace_name);
    auto stem = basename_no_ext(base_path);
    auto hpp_path = std::string{base_path} + ".hpp";
    auto cpp_path = std::string{base_path} + ".cpp";

    auto pal_words = pack.planes.total_bytes() / 2;
    auto tile_words = pack.tile_bytes / 2;
    auto pal_elem_type = (opts.chipset == Chipset::ocs)
        ? std::string_view{"std::uint16_t"}
        : std::string_view{"std::uint32_t"};
    (void)pal_words; (void)tile_words;

    // -------------------- header --------------------
    {
        std::ofstream hpp{hpp_path};
        if (!hpp) {
            return std::unexpected{Error{ErrorCode::write_failed,
                std::format("cannot open {}", hpp_path)}};
        }
        hpp << "// Generated by png2amiga-assets — do not edit.\n";
        hpp << "// Source tilesheet: " << stem << "\n";
        hpp << "#pragma once\n\n";
        hpp << "#include <array>\n";
        hpp << "#include <cstdint>\n\n";

        emit_ns_open(hpp, ns_parts);
        hpp << "\n";

        // Metadata constants
        hpp << std::format("inline constexpr unsigned tile_w         = {};\n", pack.planes.width);
        hpp << std::format("inline constexpr unsigned tile_h         = {};\n",
            pack.num_unique_tiles > 0 ? pack.planes.height / pack.num_unique_tiles : 0);
        hpp << std::format("inline constexpr unsigned depth          = {};\n", pack.planes.depth);
        hpp << std::format("inline constexpr unsigned bytes_per_row  = {};\n", pack.bytes_per_row);
        hpp << std::format("inline constexpr unsigned tile_bytes     = {};\n", pack.tile_bytes);
        hpp << std::format("inline constexpr unsigned num_tiles      = {};\n", pack.num_unique_tiles);
        hpp << std::format("inline constexpr unsigned map_w          = {};\n", pack.map_w);
        hpp << std::format("inline constexpr unsigned map_h          = {};\n", pack.map_h);
        hpp << std::format("inline constexpr unsigned num_cells      = {};\n", pack.num_cells);
        hpp << std::format("inline constexpr unsigned palette_size   = {};\n", pack.palette.size());
        hpp << "\n";

        // Tilemap cell type
        hpp <<
            "struct MapCell {\n"
            "    std::uint16_t raw;\n"
            "    [[nodiscard]] constexpr std::uint16_t index() const noexcept {\n"
            "        return static_cast<std::uint16_t>(raw & 0x3FFFu);\n"
            "    }\n"
            "    [[nodiscard]] constexpr bool h_flip() const noexcept {\n"
            "        return (raw & 0x8000u) != 0;\n"
            "    }\n"
            "    [[nodiscard]] constexpr bool v_flip() const noexcept {\n"
            "        return (raw & 0x4000u) != 0;\n"
            "    }\n"
            "};\n"
            "static_assert(sizeof(MapCell) == 2);\n\n";

        // Declarations
        hpp << std::format(
            "extern const std::array<std::uint16_t, num_tiles * (tile_bytes / 2)> tiles_data;\n"
            "extern const std::array<MapCell, num_cells> tilemap;\n"
            "extern const std::array<{}, palette_size> palette;\n\n",
            pal_elem_type);

        // Convenience helpers
        hpp <<
            "[[nodiscard]] constexpr const std::uint16_t* tile_ptr(std::uint16_t idx) noexcept {\n"
            "    return tiles_data.data() + static_cast<std::size_t>(idx) * (tile_bytes / 2);\n"
            "}\n\n";
        hpp << std::format(
            "[[nodiscard]] constexpr MapCell cell_at(unsigned x, unsigned y) noexcept {{\n"
            "    return tilemap[y * map_w + x];\n"
            "}}\n\n");

        emit_ns_close(hpp, ns_parts);
        (void)short_name;
    }

    // -------------------- source --------------------
    {
        std::ofstream cpp{cpp_path};
        if (!cpp) {
            return std::unexpected{Error{ErrorCode::write_failed,
                std::format("cannot open {}", cpp_path)}};
        }
        cpp << "// Generated by png2amiga-assets — do not edit.\n";
        cpp << "#include \"" << std::filesystem::path{hpp_path}.filename().string() << "\"\n";
        if (opts.chip_attr == "PA_ASSET_CHIP") {
            cpp << "#include \"pa/chip_attr.hpp\"\n";
        }
        cpp << "\n";

        emit_ns_open(cpp, ns_parts);
        cpp << "\n";

        // tiles_data
        if (!opts.chip_attr.empty()) cpp << opts.chip_attr << "\n";
        cpp << "const std::array<std::uint16_t, num_tiles * (tile_bytes / 2)> tiles_data = {\n";
        emit_bitplane_words(cpp, pack.planes.data);
        cpp << "};\n\n";

        // tilemap
        cpp << "const std::array<MapCell, num_cells> tilemap = {\n";
        emit_tilemap(cpp, pack.tilemap, pack.map_w);
        cpp << "};\n\n";

        // palette
        cpp << std::format("const std::array<{}, palette_size> palette = {{\n", pal_elem_type);
        emit_palette(cpp, pack.palette, opts.chipset);
        cpp << "};\n\n";

        emit_ns_close(cpp, ns_parts);
    }

    return {};
}

Result<void> write_strip_pack(std::string_view base_path,
                              const strip_pack::PackResult& pack,
                              const Options& opts) {
    auto ns_parts = split_namespace(opts.namespace_name);
    auto stem = basename_no_ext(base_path);
    auto hpp_path = std::string{base_path} + ".hpp";
    auto cpp_path = std::string{base_path} + ".cpp";

    auto pal_elem_type = (opts.chipset == Chipset::ocs)
        ? std::string_view{"std::uint16_t"}
        : std::string_view{"std::uint32_t"};

    // -------------------- header --------------------
    {
        std::ofstream hpp{hpp_path};
        if (!hpp) {
            return std::unexpected{Error{ErrorCode::write_failed,
                std::format("cannot open {}", hpp_path)}};
        }
        hpp << "// Generated by png2amiga-assets — do not edit.\n";
        hpp << "// Source strip: " << stem << "\n";
        hpp << "#pragma once\n\n";
        hpp << "#include <array>\n";
        hpp << "#include <cstdint>\n\n";

        emit_ns_open(hpp, ns_parts);
        hpp << "\n";

        hpp << std::format("inline constexpr unsigned frame_w         = {};\n", pack.frame_w);
        hpp << std::format("inline constexpr unsigned frame_h         = {};\n", pack.frame_h);
        hpp << std::format("inline constexpr unsigned storage_w       = {};\n", pack.storage_w);
        hpp << std::format("inline constexpr unsigned depth           = {};\n", pack.planes.depth);
        hpp << std::format("inline constexpr unsigned bytes_per_row   = {};\n", pack.bytes_per_row);
        hpp << std::format("inline constexpr unsigned frame_bytes     = {};\n", pack.frame_bytes);
        hpp << std::format("inline constexpr unsigned num_frames      = {};\n", pack.num_frames);
        hpp << std::format("inline constexpr unsigned preshift        = {};\n", pack.preshift);
        hpp << std::format("inline constexpr unsigned palette_size    = {};\n", pack.palette.size());
        hpp << std::format("inline constexpr bool     has_mask        = {};\n",
                           pack.has_mask ? "true" : "false");
        if (pack.has_mask) {
            hpp << std::format("inline constexpr unsigned mask_bytes      = {};\n", pack.mask_bytes);
        }
        hpp << "\n";

        hpp << std::format(
            "extern const std::array<std::uint16_t, num_frames * preshift * (frame_bytes / 2)> frames_data;\n");
        if (pack.has_mask) {
            hpp << std::format(
                "extern const std::array<std::uint16_t, num_frames * preshift * (mask_bytes / 2)> mask_data;\n");
        }
        hpp << std::format(
            "extern const std::array<{}, palette_size> palette;\n\n", pal_elem_type);

        hpp <<
            "// Returns the bitplane data for frame n with horizontal sub-word\n"
            "// shift k in [0, preshift). For preshift==1, k is ignored.\n"
            "[[nodiscard]] constexpr const std::uint16_t* frame_ptr(unsigned n, unsigned k = 0) noexcept {\n"
            "    return frames_data.data() + (static_cast<std::size_t>(n) * preshift + k) * (frame_bytes / 2);\n"
            "}\n";
        if (pack.has_mask) {
            hpp <<
                "[[nodiscard]] constexpr const std::uint16_t* mask_ptr(unsigned n, unsigned k = 0) noexcept {\n"
                "    return mask_data.data() + (static_cast<std::size_t>(n) * preshift + k) * (mask_bytes / 2);\n"
                "}\n";
        }
        hpp <<
            "// Select the pre-shifted copy for a target X coordinate.\n"
            "// Engine usage: auto* p = frame_ptr(f, shift_for_x(target_x));\n"
            "[[nodiscard]] constexpr unsigned shift_for_x(unsigned x) noexcept {\n"
            "    return preshift <= 1 ? 0u : (x & 15u) / (16u / preshift);\n"
            "}\n\n";

        emit_ns_close(hpp, ns_parts);
    }

    // -------------------- source --------------------
    {
        std::ofstream cpp{cpp_path};
        if (!cpp) {
            return std::unexpected{Error{ErrorCode::write_failed,
                std::format("cannot open {}", cpp_path)}};
        }
        cpp << "// Generated by png2amiga-assets — do not edit.\n";
        cpp << "#include \"" << std::filesystem::path{hpp_path}.filename().string() << "\"\n";
        if (opts.chip_attr == "PA_ASSET_CHIP") {
            cpp << "#include \"pa/chip_attr.hpp\"\n";
        }
        cpp << "\n";

        emit_ns_open(cpp, ns_parts);
        cpp << "\n";

        if (!opts.chip_attr.empty()) cpp << opts.chip_attr << "\n";
        cpp << "const std::array<std::uint16_t, num_frames * preshift * (frame_bytes / 2)> frames_data = {\n";
        emit_bitplane_words(cpp, pack.planes.data);
        cpp << "};\n\n";

        if (pack.has_mask) {
            if (!opts.chip_attr.empty()) cpp << opts.chip_attr << "\n";
            cpp << "const std::array<std::uint16_t, num_frames * preshift * (mask_bytes / 2)> mask_data = {\n";
            emit_bitplane_words(cpp, pack.mask_data);
            cpp << "};\n\n";
        }

        cpp << std::format("const std::array<{}, palette_size> palette = {{\n", pal_elem_type);
        emit_palette(cpp, pack.palette, opts.chipset);
        cpp << "};\n\n";

        emit_ns_close(cpp, ns_parts);
    }

    return {};
}

